-- 1. Create the 'devices' table
create table if not exists public.devices (
  id bigint generated by default as identity primary key,
  slug text unique not null,
  name text not null,
  brand text not null,
  category text not null default 'phone',
  storage text not null,
  storage_options jsonb default '[]'::jsonb,
  condition text not null default 'UK Used',
  colors jsonb default '[]'::jsonb,
  image text not null,
  images jsonb default '[]'::jsonb,
  featured boolean not null default true,
  in_stock boolean not null default true,
  tagline text default '',
  overview text default '',
  specs jsonb default '{}'::jsonb,
  price_note text default 'Price on daily request (market rate)',
  created_at timestamptz default now()
);

-- 2. Indexes for instant querying
create index if not exists idx_devices_slug on public.devices (slug);
create index if not exists idx_devices_category on public.devices (category);
create index if not exists idx_devices_brand on public.devices (brand);
create index if not exists idx_devices_created on public.devices (created_at desc);

-- 3. Row Level Security (RLS)
alter table public.devices enable row level security;

-- Allow public read access to all catalog listings
drop policy if exists "Allow public read access on devices" on public.devices;
create policy "Allow public read access on devices"
  on public.devices
  for select
  using (true);

-- Allow full management for server operations
drop policy if exists "Allow full management on devices" on public.devices;
create policy "Allow full management on devices"
  on public.devices
  for all
  using (true)
  with check (true);

-- 4. Storage Bucket Setup for Product Images
insert into storage.buckets (id, name, public)
values ('device-photos', 'device-photos', true)
on conflict (id) do nothing;

drop policy if exists "Allow public viewing of device photos" on storage.objects;
create policy "Allow public viewing of device photos"
  on storage.objects
  for select
  using (bucket_id = 'device-photos');

drop policy if exists "Allow uploading device photos" on storage.objects;
create policy "Allow uploading device photos"
  on storage.objects
  for insert
  with check (bucket_id = 'device-photos');

drop policy if exists "Allow updating device photos" on storage.objects;
create policy "Allow updating device photos"
  on storage.objects
  for update
  using (bucket_id = 'device-photos');

drop policy if exists "Allow deleting device photos" on storage.objects;
create policy "Allow deleting device photos"
  on storage.objects
  for delete
  using (bucket_id = 'device-photos');
